const DICTS: Record<ShopLang, Record<ShopStringKey, string>> = { ro, ru, en };

export type ShopT = (key: ShopStringKey, vars?: Record<string, string | number>) => string;

/** The language a translator speaks (its `shopLangCode`). */
export function shopLangOfT(t: ShopT): ShopLang {
  return parseShopLang(t("shopLangCode"));
}

/** Translator for one language; `{name}` placeholders are filled from `vars`. */
export function shopT(lang: ShopLang): ShopT {
  const dict = DICTS[lang];
  return (key, vars) => {
    const template: string = dict[key] ?? DICTS.ro[key] ?? key;
    if (!vars) return template;
    return template
      .replace(/\{(\w+)\|([^{}]*)\}/g, (m, name: string, forms: string) =>
        name in vars ? pluralWord(Number(vars[name]), forms.split("|"), lang) : m,
      )
      .replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
  };
}

/**
 * Plural form index for `n`: Romanian «1 fișier / 2 fișiere / 20 de fișiere»
 * (like `itemsLabel`), Russian «1 файл / 2 файла / 5 файлов», English
 * «1 file / 2 files» (one / other).
 */
export function pluralIndex(n: number, lang: ShopLang): 0 | 1 | 2 {
  const abs: number = Math.abs(Math.trunc(n));
  const m100: number = abs % 100;
  if (lang === "ru") {
    const m10: number = abs % 10;
    if (m10 === 1 && m100 !== 11) return 0;
    return m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? 1 : 2;
  }
  if (abs === 1) return 0;
  if (lang === "en") return 1;
  return abs === 0 || (m100 >= 1 && m100 <= 19) ? 1 : 2;
}

/** Template plural `{n|one|few|many}` (English: `{n|one|other}`); a missing form falls back to the last one. */
function pluralWord(n: number, forms: readonly string[], lang: ShopLang): string {
  const i: number = pluralIndex(n, lang);
  return forms[Math.min(i, forms.length - 1)] ?? "";
}

export function pickLocalized(value: Localized, lang: ShopLang): string {
  return value[lang] || value.ro;
}

/**
 * «1 produs / 2 produse / 20 de produse», «1 товар / 2 товара / 5 товаров»,
 * «1 item / 2 items».
 * Romanian adds «de» when the number ends in 00 or 20–99 (0 and 1–19 do not).
 */
export function itemsLabel(n: number, lang: ShopLang): string {
  const abs: number = Math.abs(Math.trunc(n));
  if (lang === "ru") {
    const m10: number = abs % 10;
    const m100: number = abs % 100;
    const word: string =
      m10 === 1 && m100 !== 11 ? "товар" : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? "товара" : "товаров";
    return `${n} ${word}`;
  }
  if (lang === "en") return `${n} ${abs === 1 ? "item" : "items"}`;
  if (abs === 1) return `${n} produs`;
  const m100: number = abs % 100;
  return m100 >= 1 && m100 <= 19 ? `${n} produse` : abs === 0 ? `${n} produse` : `${n} de produse`;
}
