/** «1 fișier» / «3 fișiere» / «20 de fișiere». */
function plural(n: number, one: string, few: string): string {
  if (n === 1) return `1 ${one}`;
  const m100 = n % 100;
  return n === 0 || (m100 >= 1 && m100 <= 19) ? `${n} ${few}` : `${n} de ${few}`;
}

