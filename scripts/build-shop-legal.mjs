#!/usr/bin/env node
/**
 * Storefront legal pages (/termeni, /retur, /confidentialitate): copies the
 * drafts in `docs/legal/<name>.md` (RO section first, then RU, then EN, each
 * starting with a `# ` heading and separated by `---`; an optional leading
 * «draft» blockquote + `---` is dropped) into
 * `src/lib/storefront/legalTexts.generated.ts`, so the pages do not read
 * files at runtime. A file without an EN section still builds: the English
 * page then shows the Romanian text (with a warning here). Missing files →
 * null (the page shows a placeholder). Run after editing the drafts:
 *
 *   node scripts/build-shop-legal.mjs
 */
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const NAMES = ["termeni", "retur", "confidentialitate"];

/** Sections of a draft by `# ` heading, without the trailing `---` separator. */
function splitLegal(md) {
  const lines = md.replace(/\r\n/g, "\n").split("\n");
  const h1 = lines.map((l, i) => (/^# /.test(l) ? i : -1)).filter((i) => i >= 0);
  if (h1.length < 2) return null;
  const section = (k) =>
    lines
      .slice(h1[k], h1[k + 1])
      .join("\n")
      .trim()
      .replace(/\n+-{3,}\s*$/, "")
      .trim();
  const ro = section(0);
  const ru = section(1);
  const en = h1.length >= 3 ? section(2) : null;
  return { ro, ru, en };
}

const out = {};
const warnings = [];
for (const name of NAMES) {
  const file = path.join(root, "docs", "legal", `${name}.md`);
  const parts = fs.existsSync(file) ? splitLegal(fs.readFileSync(file, "utf8")) : null;
  if (parts && !parts.en) warnings.push(`${name}: no EN section, English page falls back to RO`);
  out[name] = parts ? { ro: parts.ro, ru: parts.ru, en: parts.en ?? parts.ro } : null;
}

const body = `// Generated by scripts/build-shop-legal.mjs from docs/legal/*.md — do not edit by hand.

import type { ShopLang } from "./i18n";

export type ShopLegalDoc = "termeni" | "retur" | "confidentialitate";

/** Markdown per page and language (every shop language required); null = no draft yet (placeholder page). */
export const SHOP_LEGAL_TEXTS: Record<ShopLegalDoc, Record<ShopLang, string> | null> = ${JSON.stringify(out, null, 2)};
`;
fs.writeFileSync(path.join(root, "src/lib/storefront/legalTexts.generated.ts"), body);
console.log("legal texts:", NAMES.map((n) => `${n}=${out[n] ? "ok" : "missing"}`).join(" "));
for (const w of warnings) console.warn("warning:", w);
