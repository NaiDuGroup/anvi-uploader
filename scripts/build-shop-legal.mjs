#!/usr/bin/env node
/**
 * Storefront legal pages (/termeni, /retur, /confidentialitate): copies the
 * drafts in `docs/legal/<name>.md` (RO section first, then RU, each starting
 * with a `# ` heading; an optional leading «draft» blockquote + `---` is
 * dropped) into `src/lib/storefront/legalTexts.generated.ts`, so the pages do
 * not read files at runtime. Missing files → null (the page shows a
 * placeholder). Run after editing the drafts:
 *
 *   node scripts/build-shop-legal.mjs
 */
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const NAMES = ["termeni", "retur", "confidentialitate"];

function split(md) {
  const lines = md.replace(/\r\n/g, "\n").split("\n");
  const h1 = lines.map((l, i) => (/^# /.test(l) ? i : -1)).filter((i) => i >= 0);
  if (h1.length < 2) return null;
  const ro = lines.slice(h1[0], h1[1]).join("\n").replace(/\n-{3,}\s*$/m, "").trim();
  const ru = lines.slice(h1[1]).join("\n").trim();
  return { ro: ro.replace(/\n+---\s*$/, "").trim(), ru };
}

const out = {};
for (const name of NAMES) {
  const file = path.join(root, "docs", "legal", `${name}.md`);
  out[name] = fs.existsSync(file) ? split(fs.readFileSync(file, "utf8")) : null;
}

const body = `// Generated by scripts/build-shop-legal.mjs from docs/legal/*.md — do not edit by hand.

export type ShopLegalDoc = "termeni" | "retur" | "confidentialitate";

/** Markdown per page and language; null = no draft yet (placeholder page). */
export const SHOP_LEGAL_TEXTS: Record<ShopLegalDoc, { ro: string; ru: string } | null> = ${JSON.stringify(out, null, 2)};
`;
fs.writeFileSync(path.join(root, "src/lib/storefront/legalTexts.generated.ts"), body);
console.log("legal texts:", NAMES.map((n) => `${n}=${out[n] ? "ok" : "missing"}`).join(" "));
