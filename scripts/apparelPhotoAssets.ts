/**
 * Builds the apparel Studio's photo assets (re-runnable):
 *
 *   npx tsx scripts/apparelPhotoAssets.ts [photoCacheDir]
 *
 * For every calibrated view (`PHOTO_VIEWS`): the supplier's HD photos
 * (static.gorfactory.es, public) → `public/studio/apparel/<model>/<view>-<colour>.webp`
 * (1200 px, one per shipped colour) and `<view>-maps.png` (fabric shade,
 * displacement and cut-out over the garment, from the white and black
 * photos), plus `src/lib/studio/apparelPhotoAssets.gen.ts` (where the maps
 * sit, the garment's bounds, sizes). The browser then only composites.
 */
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";
import {
  APPAREL_ASSET_PX,
  PHOTO_VIEWS,
  PHOTO_VIEW_KEYS,
  apparelMapsAsset,
  apparelPhotoAsset,
  buildFabricMaps,
  encodeFabricMaps,
  garmentMask,
  maskBounds,
  photoUrl,
  type Raster,
  type Rect,
} from "@/lib/studio/photoMockup";

const ROOT: string = path.resolve(__dirname, "..");
const CACHE: string | undefined = process.argv[2];

async function hd(url: string): Promise<Buffer> {
  const local: string | undefined = CACHE ? path.join(CACHE, url.split("/").pop()!) : undefined;
  if (local && fs.existsSync(local)) return fs.readFileSync(local);
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  const buf = Buffer.from(await res.arrayBuffer());
  if (local) fs.writeFileSync(local, buf);
  return buf;
}

async function raster(buf: Buffer, px: number): Promise<Raster> {
  const { data, info } = await sharp(buf).resize(px, px, { fit: "fill", kernel: "lanczos3" }).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  return { width: info.width, height: info.height, data: new Uint8ClampedArray(data.buffer, data.byteOffset, data.length) };
}

function maxMask(a: Raster, b: Raster): Raster {
  const data = new Uint8ClampedArray(a.data);
  for (let i = 0; i < data.length; i += 4) {
    const v: number = Math.max(a.data[i]!, b.data[i]!);
    data[i] = data[i + 1] = data[i + 2] = v;
  }
  return { width: a.width, height: a.height, data };
}

async function main(): Promise<void> {
  const entries: string[] = [];
  let total = 0;
  for (const key of PHOTO_VIEW_KEYS) {
    const cal = PHOTO_VIEWS[key]!;
    const scale: number = APPAREL_ASSET_PX / cal.sizePx;
    const dir: string = path.join(ROOT, "public", path.dirname(apparelPhotoAsset(cal, "01")));
    fs.mkdirSync(dir, { recursive: true });
    let bytes = 0;
    for (const c of cal.colours) {
      const out: string = path.join(ROOT, "public", apparelPhotoAsset(cal, c));
      await sharp(await hd(photoUrl(cal, c)))
        .resize(APPAREL_ASSET_PX, APPAREL_ASSET_PX, { fit: "fill", kernel: "lanczos3" })
        .webp({ quality: 82, effort: 6 })
        .toFile(out);
      bytes += fs.statSync(out).size;
    }
    const white: Raster = await raster(await hd(photoUrl(cal, cal.shadeColour)), APPAREL_ASSET_PX);
    // The cut-out: the dark photo's garment, plus whatever is dark on the white one (the cap's
    // sandwich trim is white on every colour but white: the black photo alone would cut it away).
    const mask: Raster = maxMask(
      garmentMask(await raster(await hd(photoUrl(cal, cal.maskColour)), APPAREL_ASSET_PX), scale),
      garmentMask(white, scale),
    );
    const garment: Rect = maskBounds(mask, 0);
    const rect: Rect = maskBounds(mask, 4);
    const maps = encodeFabricMaps(buildFabricMaps(white, mask, rect, { reliefPx: cal.reliefPx, scale, shadeBlurPx: 5 }));
    const mapsOut: string = path.join(ROOT, "public", apparelMapsAsset(cal));
    await sharp(Buffer.from(maps.data.buffer, maps.data.byteOffset, maps.data.length), { raw: { width: maps.width, height: maps.height, channels: 4 } })
      .png({ compressionLevel: 9, palette: false })
      .toFile(mapsOut);
    bytes += fs.statSync(mapsOut).size;
    total += bytes;
    entries.push(`  "${key}": { maps: ${JSON.stringify(rect)}, garment: ${JSON.stringify(garment)}, bytes: ${bytes} },`);
    console.log(key, cal.colours.join(","), `${Math.round(bytes / 1024)} KB`);
  }
  const ts = `// Generated by scripts/apparelPhotoAssets.ts — do not edit by hand.
import type { PhotoViewKey, Rect } from "./photoMockup";

/** Per view, at APPAREL_ASSET_PX: where the maps image sits on the photo, the garment's bounds, asset bytes. */
export const APPAREL_PHOTO_ASSETS: Record<PhotoViewKey, { maps: Rect; garment: Rect; bytes: number }> = {
${entries.join("\n")}
};
`;
  fs.writeFileSync(path.join(ROOT, "src/lib/studio/apparelPhotoAssets.gen.ts"), ts);
  console.log(`total ${(total / 1024 / 1024).toFixed(2)} MB`);
}

void main();
